using Microsoft.AspNetCore.Mvc;
using NtisPlatform.Core.Models;

namespace NtisPlatform.Api.Controllers;

public partial class PropertyController
{
    /// <summary>
    /// Splits an existing property into one or more new sub-properties with sequential alphabetic suffixes (A, B, ... Z, AA, AB, ...).
    /// Each new property is cloned from the parent and assigned a unique property number.
    /// </summary>
    /// <param name="dto">The split request containing the base property number, ward, and number of splits to generate.</param>
    /// <param name="cancellationToken">Cancellation token.</param>
    /// <returns>A <see cref="PropertySplitResultDto"/> containing the created and skipped split properties and mapped old property IDs.</returns>
    /// <response code="200">Split properties created successfully.</response>
    /// <response code="500">An unexpected error occurred.</response>
    [HttpPost("split-property")]
    [ProducesResponseType(typeof(PropertySplitResultDto), StatusCodes.Status200OK)]
    [ProducesResponseType(StatusCodes.Status500InternalServerError)]
    public async Task<IActionResult> SplitProperty([FromBody] PropertySplitCreateDto dto, CancellationToken cancellationToken = default)
        => Ok(await _propertyService.SplitProperty(dto, cancellationToken));

    /// <summary>
    /// Retrieves a list of properties or partitions that were generated by splitting the specified base property/partition.
    /// If PartitionNo is provided, it retrieves partition splits. Otherwise, it retrieves property splits.
    /// </summary>
    /// <param name="request">The request containing the base property number, optional partition number, and ward ID.</param>
    /// <param name="cancellationToken">Cancellation token.</param>
    /// <returns>A list of <see cref="PropertyHierarchyResponseDto"/> containing the split properties/partitions.</returns>
    [HttpGet("show-property-list")]
    [ProducesResponseType(typeof(List<PropertyHierarchyResponseDto>), StatusCodes.Status200OK)]
    [ProducesResponseType(StatusCodes.Status500InternalServerError)]
    public async Task<IActionResult> GetPropertyList([FromQuery] PropertyLookupRequestDto request, CancellationToken cancellationToken = default)
        => Ok(await _propertyService.GetPropertyListAsync(request, cancellationToken));
}
