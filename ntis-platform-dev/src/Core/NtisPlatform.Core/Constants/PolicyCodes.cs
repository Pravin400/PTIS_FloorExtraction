namespace NtisPlatform.Core.Constants;

/// <summary>
/// Well-known PolicyCodeMaster.PolicyCode values consumed by the Occupation Tax engine.
/// OC/CC/ElectricBill intentionally share their string value with
/// <see cref="CertificateTypeCodes"/> since one certificate type maps onto one policy code
/// family. Each DATE_BASED family has two codes: the plain code tags a full finance-year
/// PolicyTaxDetails row, the PARTIAL_x code tags the prorated onset-year row (BR1/BR5) — chained
/// via PolicyCodeMaster.NextPolicyCodeId (e.g. OcPartial -> Oc). Business-final naming is
/// PARTIAL_CC/PARTIAL_OC/PARTIAL_ELECTRIC_BILL (the "PARTIAL_" prefix comes first); the older
/// CC_PARTIAL/OC_PARTIAL/ELECTRIC_PARTIAL naming is retired, not kept as an alias, since this
/// feature has not yet been deployed with seeded data under the old names.
/// </summary>
public static class PolicyCodes
{
    public const string Oc = CertificateTypeCodes.OC;
    public const string OcPartial = "PARTIAL_OC";

    public const string Cc = CertificateTypeCodes.CC;
    public const string CcPartial = "PARTIAL_CC";

    public const string ElectricBill = CertificateTypeCodes.ElectricBill;

    /// <summary>Electric Bill's partial-year code (the prorated onset year of an electricity-bill start).</summary>
    public const string ElectricPartial = "PARTIAL_ELECTRIC_BILL";

    /// <summary>
    /// Retrospective tax of a rule that has no start certificate at all (TaxStartMode MAX_LOOK_BACK_DATE /
    /// CONSTRUCTION_YEAR with no StartEvidenceTypeId): the no-certificate fallback and the other look-back rules.
    /// Booked under its own code so a property without any electricity bill is not shown as an electricity-bill
    /// demand. A database that does not have these two rows yet falls back to <see cref="ElectricBill"/> /
    /// <see cref="ElectricPartial"/>, the codes these rules used before (see the engine's family resolution).
    /// </summary>
    public const string DirectRetro = "DIRECT_RETRO";

    /// <summary>The prorated onset-year code of <see cref="DirectRetro"/>.</summary>
    public const string DirectRetroPartial = "PARTIAL_DIRECT_RETRO";

    /// <summary>The Rateable Value pipeline's base annual tax policy (unrelated to certificates).</summary>
    public const string NetTax = "NETTAX";

    /// <summary>
    /// Historical pending tax amount brought into PTIS.TransMast during ULB migration -- NOT
    /// retro demand generated by the Retrospective Tax engine (PolicyCodeMaster.IsRetroDemand = 0
    /// for this code). A finance year's OLD_ARREARS row is deactivated (not deleted) once that
    /// same year gets a real retro-policy recalculation, since only one demand should be active
    /// per PropertyId + FinanceYearId + CalculationType + TaxId.
    /// </summary>
    public const string OldArrears = "OLD_ARREARS";

    /// <summary>
    /// Section 129A stage-based family, chained via PolicyCodeMaster.NextPolicyCodeId:
    /// Section129Old1 -> Section129Old2 -> Section129_20 -> ... -> Section129Final
    /// (Section129Final is IsFinalStage = 1, so resolving its next stage yields itself again).
    /// </summary>
    public const string Section129Old1 = "SECTION_129_OLD_1";
    public const string Section129Old2 = "SECTION_129_OLD_2";
    public const string Section129_20 = "SECTION_129_20";
    public const string Section129_40 = "SECTION_129_40";
    public const string Section129_60 = "SECTION_129_60";
    public const string Section129_80 = "SECTION_129_80";
    public const string Section129Final = "SECTION_129_100";
}
