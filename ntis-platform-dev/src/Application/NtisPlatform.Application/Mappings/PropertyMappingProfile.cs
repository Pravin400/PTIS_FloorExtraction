using AutoMapper;
using NtisPlatform.Application.DTOs.Property;
using NtisPlatform.Application.DTOs.PropertyDetails;
using NtisPlatform.Core.Models;
using NtisPlatform.Core.Entities;

namespace NtisPlatform.Application.Mappings;

/// <summary>
/// Global Property Mapping Profile
/// Maps PropertyEntity to PropertyDto with all PropertyMast fields
/// </summary>
public class PropertyMappingProfile : Profile
{
    public PropertyMappingProfile()
    {
        CreateMap<PropertyEntity, PropertyDto>();

        // CreateDto to Entity
        CreateMap<CreatePropertyDto, PropertyEntity>()
            .ForMember(dest => dest.Id, opt => opt.Ignore()) // Auto-generated by database
            .ForMember(dest => dest.CreatedDate, opt => opt.Ignore()) // Managed by Repository (BaseEntity handling)
            .ForMember(dest => dest.UpdatedDate, opt => opt.Ignore()) // Managed by Repository on update
            .ForMember(dest => dest.CreatedBy, opt => opt.MapFrom(src => src.CreatedBy));

        // CreateNewPropertyDto (Range/Single generation) to Entity
        CreateMap<CreateNewPropertyDto, PropertyEntity>()
            .ForMember(dest => dest.Id, opt => opt.Ignore())
            .ForMember(dest => dest.UpdatedDate, opt => opt.Ignore())
            .ForMember(dest => dest.UpdatedBy, opt => opt.Ignore());

        // CreateNewPropertyDto to PropertyDetailsEntity
        CreateMap<CreateNewPropertyDto, PropertyDetailsEntity>()
            .ForMember(dest => dest.Id, opt => opt.Ignore())
            .ForMember(dest => dest.PropertyId, opt => opt.Ignore())
            .ForMember(dest => dest.CreatedDate, opt => opt.Ignore())
            .ForMember(dest => dest.UpdatedDate, opt => opt.Ignore())
            .ForMember(dest => dest.UpdatedBy, opt => opt.Ignore())
            .ForMember(dest => dest.FloorId, opt => opt.MapFrom(src => src.FloorId > 0 ? (int?)src.FloorId : null))
            .ForMember(dest => dest.ConstructionTypeId, opt => opt.MapFrom(src => src.ConstructionTypeId > 0 ? (int?)src.ConstructionTypeId : null))
            .ForMember(dest => dest.TypeOfUseId, opt => opt.MapFrom(src => src.TypeOfUseId))
            .ForMember(dest => dest.IsActive, opt => opt.MapFrom(src => true))
            .ForMember(dest => dest.MarkedForDeletion, opt => opt.MapFrom(src => false));

        // CreateNewPropertyDto to RoomWiseSubmissionDetailsEntity
        CreateMap<CreateNewPropertyDto, RoomWiseSubmissionDetailsEntity>()
            .ForMember(dest => dest.Id, opt => opt.Ignore())
            .ForMember(dest => dest.PropertyId, opt => opt.Ignore())
            .ForMember(dest => dest.PropertyDetailsId, opt => opt.Ignore())
            .ForMember(dest => dest.CreatedDate, opt => opt.Ignore())
            .ForMember(dest => dest.UpdatedDate, opt => opt.Ignore())
            .ForMember(dest => dest.UpdatedBy, opt => opt.Ignore())
            .ForMember(dest => dest.OuterYesNo, opt => opt.MapFrom(src => false))
            .ForMember(dest => dest.MinusYesNo, opt => opt.MapFrom(src => false))
            .ForMember(dest => dest.IsActive, opt => opt.MapFrom(src => true));

        // CreateNewPropertyDto to PropertyAssessmentEntity
        CreateMap<CreateNewPropertyDto, PropertyAssessmentEntity>()
            .ForMember(dest => dest.Id, opt => opt.Ignore())
            .ForMember(dest => dest.PropertyId, opt => opt.Ignore())
            .ForMember(dest => dest.AdharCardNo, opt => opt.MapFrom(src => src.AdharCardNo))
            .ForMember(dest => dest.CreatedDate, opt => opt.Ignore())
            .ForMember(dest => dest.UpdatedDate, opt => opt.Ignore())
            .ForMember(dest => dest.UpdatedBy, opt => opt.Ignore())
            .ForMember(dest => dest.IsActive, opt => opt.MapFrom(src => true))
            .ForMember(dest => dest.MarkedForDeletion, opt => opt.MapFrom(src => false));

        // CreateNewPropertyDto to PropertyWorkflowDetailsEntity
        CreateMap<CreateNewPropertyDto, PropertyWorkflowDetailsEntity>()
            .ForMember(dest => dest.Id, opt => opt.Ignore())
            .ForMember(dest => dest.PropertyId, opt => opt.Ignore())
            .ForMember(dest => dest.WorkflowStageId, opt => opt.MapFrom(src => src.WorkflowStageId))
            .ForMember(dest => dest.CurrentStatus, opt => opt.MapFrom(src => true))
            .ForMember(dest => dest.CreatedDate, opt => opt.MapFrom(src => src.CreatedDate ?? DateTime.UtcNow))
            .ForMember(dest => dest.UpdatedDate, opt => opt.Ignore())
            .ForMember(dest => dest.UpdatedBy, opt => opt.Ignore())
            .ForMember(dest => dest.IsActive, opt => opt.MapFrom(src => true));

        // UpdateDto to Entity
        CreateMap<UpdatePropertyDto, PropertyEntity>()
            .ForMember(dest => dest.Id, opt => opt.Ignore()) 
            .ForMember(dest => dest.CreatedDate, opt => opt.Ignore()) 
            .ForMember(dest => dest.UpdatedDate, opt => opt.Ignore()) 
            .ForMember(dest => dest.UpdatedBy, opt => opt.MapFrom(src => src.UpdatedBy));

        // UpdateAllPropertyDetailsDto to Entities
        CreateMap<UpdateAllPropertyDetailsDto, PropertyEntity>()
            .ForMember(dest => dest.Id, opt => opt.Ignore())
            .ForMember(dest => dest.CreatedDate, opt => opt.Ignore())
            .ForMember(dest => dest.CreatedBy, opt => opt.Ignore())
            .ForMember(dest => dest.UpdatedDate, opt => opt.Ignore())
            .ForMember(dest => dest.UPICId, opt => opt.Ignore())
            .ForMember(dest => dest.OccupierTypeId, opt =>
            {
                opt.Condition(src => src.OccupierTypeId.HasValue);
                opt.MapFrom(src => src.OccupierTypeId);
            });

        CreateMap<UpdateAllPropertyDetailsDto, SocietyDetailsEntity>()
            .ForMember(dest => dest.Id, opt => opt.Ignore())
            .ForMember(dest => dest.PropertyId, opt => opt.Ignore())
            .ForMember(dest => dest.CreatedDate, opt => opt.Ignore())
            .ForMember(dest => dest.CreatedBy, opt => opt.Ignore())
            .ForMember(dest => dest.UpdatedDate, opt => opt.Ignore());

        CreateMap<UpdateAllPropertyDetailsDto, PropertyAssessmentEntity>()
            .ForMember(dest => dest.Id, opt => opt.Ignore())
            .ForMember(dest => dest.PropertyId, opt => opt.Ignore())
            .ForMember(dest => dest.OwnerTypeId, opt =>
            {
                opt.Condition(src => src.OwnerTypeId.HasValue);
                opt.MapFrom(src => src.OwnerTypeId);
            })
            .ForMember(dest => dest.AdharCardNo, opt =>
            {
                opt.Condition(src => src.AdharCardNo != null);
                opt.MapFrom(src => string.IsNullOrWhiteSpace(src.AdharCardNo) ? null : src.AdharCardNo.Trim());
            })
            .ForMember(dest => dest.CreatedDate, opt => opt.Ignore())
            .ForMember(dest => dest.CreatedBy, opt => opt.Ignore())
            .ForMember(dest => dest.UpdatedDate, opt => opt.Ignore());

        CreateMap<UpdateAllPropertyDetailsDto, PropertyDetailsEntity>()
            .ForMember(dest => dest.Id, opt => opt.Ignore())
            .ForMember(dest => dest.PropertyId, opt => opt.Ignore())
            .ForMember(dest => dest.CreatedDate, opt => opt.Ignore())
            .ForMember(dest => dest.CreatedBy, opt => opt.Ignore())
            .ForMember(dest => dest.UpdatedDate, opt => opt.Ignore());

        CreateMap<UpdateAllPropertyDetailsDto, RoomWiseSubmissionDetailsEntity>()
            .ForMember(dest => dest.Id, opt => opt.Ignore())
            .ForMember(dest => dest.PropertyId, opt => opt.Ignore())
            .ForMember(dest => dest.PropertyDetailsId, opt => opt.Ignore())
            .ForMember(dest => dest.CreatedDate, opt => opt.Ignore())
            .ForMember(dest => dest.CreatedBy, opt => opt.Ignore())
            .ForMember(dest => dest.UpdatedDate, opt => opt.Ignore())
            .ForMember(dest => dest.OuterYesNo, opt => opt.Ignore())
            .ForMember(dest => dest.MinusYesNo, opt => opt.Ignore());

        // Self-mapping for cloning PropertyEntity during split operations.
        // Ignores Id (so EF auto-generates it) and all navigation properties
        // (so EF doesn't cascade-insert related child entities).
        CreateMap<PropertyEntity, PropertyEntity>()
            .ForMember(dest => dest.Id, opt => opt.Ignore())
            .ForMember(dest => dest.CreatedDate, opt => opt.Ignore())
            .ForMember(dest => dest.UpdatedDate, opt => opt.Ignore())
            .ForMember(dest => dest.CreatedBy, opt => opt.Ignore())
            .ForMember(dest => dest.UpdatedBy, opt => opt.Ignore())
            // Master data navigation references
            .ForMember(dest => dest.TaxZone, opt => opt.Ignore())
            .ForMember(dest => dest.Ward, opt => opt.Ignore())
            .ForMember(dest => dest.Mouja, opt => opt.Ignore())
            .ForMember(dest => dest.PropertyAssessmentStatus, opt => opt.Ignore())
            // Child entity navigation collections
            .ForMember(dest => dest.FlagMaster, opt => opt.Ignore())
            .ForMember(dest => dest.PropertyTaxCalculationCVResults, opt => opt.Ignore())
            .ForMember(dest => dest.RVCalculationResults, opt => opt.Ignore())
            .ForMember(dest => dest.PropertyDetails, opt => opt.Ignore())
            .ForMember(dest => dest.PropertyDetailsOld, opt => opt.Ignore())
            .ForMember(dest => dest.PropertyMastOld, opt => opt.Ignore())
            .ForMember(dest => dest.SocietyDetailsMast, opt => opt.Ignore())
            .ForMember(dest => dest.PropertyMastDetails, opt => opt.Ignore())
            .ForMember(dest => dest.PolicyTaxDetailsCV, opt => opt.Ignore())
            .ForMember(dest => dest.PolicyTaxDetails, opt => opt.Ignore())
            .ForMember(dest => dest.ApplyTaxesMaster, opt => opt.Ignore())
            .ForMember(dest => dest.PropertyAssessmentDetails, opt => opt.Ignore())
            .ForMember(dest => dest.PropertyCertificates, opt => opt.Ignore())
            .ForMember(dest => dest.PropertyTaxCalculationSection129Results, opt => opt.Ignore())
            .ForMember(dest => dest.RoomWiseSubmissionDetails, opt => opt.Ignore())
            .ForMember(dest => dest.PropertyImagesMast, opt => opt.Ignore())
            .ForMember(dest => dest.PropertySocialDetails, opt => opt.Ignore())
            .ForMember(dest => dest.WaterConnectionMaster, opt => opt.Ignore())
            .ForMember(dest => dest.TransMast, opt => opt.Ignore())
            .ForMember(dest => dest.TransMastArchive, opt => opt.Ignore())
            .ForMember(dest => dest.TransMastLookup, opt => opt.Ignore())
            .ForMember(dest => dest.WorkflowHistory, opt => opt.Ignore());

        // UpdateAmenityDto to UpdatePropertyDto (for PropertyMast fields)
        CreateMap<UpdateAmenityDto, UpdatePropertyDto>()
            .ForMember(dest => dest.WardId, opt => opt.Ignore()) // set from existing property
            .ForMember(dest => dest.PropertyNo, opt => opt.Ignore()) // set from existing property
            .ForMember(dest => dest.TaxZoneId, opt => opt.MapFrom(src => src.TaxZoneId))
            .ForMember(dest => dest.PropertyTypeId, opt => opt.MapFrom(src => src.PropertyTypeId))
            .ForMember(dest => dest.PartitionNo, opt => opt.MapFrom(src => src.PartitionNo))
            .ForMember(dest => dest.CategoryId, opt => opt.MapFrom(src => src.CategoryId))
            .ForMember(dest => dest.OpenPlot, opt => opt.MapFrom(src => src.OpenPlot))
            .ForMember(dest => dest.IsActive, opt => opt.MapFrom(src => src.IsActive))
            .ForMember(dest => dest.UpdatedBy, opt => opt.MapFrom(src => src.UpdatedBy));

        // UpdateAmenityDto to PropertyDetailsEntity (for PropertyDetails fields)
        CreateMap<UpdateAmenityDto, PropertyDetailsEntity>()
            .ForMember(dest => dest.Id, opt => opt.Ignore())
            .ForMember(dest => dest.PropertyId, opt => opt.Ignore())
            .ForMember(dest => dest.FloorId, opt => opt.MapFrom(src => src.FloorId))
            .ForMember(dest => dest.SubFloorId, opt => opt.MapFrom(src => src.SubFloorId))
            .ForMember(dest => dest.ConstructionTypeId, opt => opt.MapFrom(src => src.ConstructionTypeId))
            .ForMember(dest => dest.TypeOfUseId, opt => opt.MapFrom(src => src.TypeOfUseId))
            .ForMember(dest => dest.SubTypeOfUseId, opt => opt.MapFrom(src => src.SubTypeOfUseId))
            .ForMember(dest => dest.NoOfRooms, opt => opt.MapFrom(src => src.NoOfRooms))
            .ForMember(dest => dest.ConstructionYear, opt => opt.MapFrom(src => src.ConstructionYear))
            .ForMember(dest => dest.AssessmentYear, opt => opt.MapFrom(src => src.AssessmentYear))
            .ForMember(dest => dest.CarpetAreaSqMeter, opt => opt.MapFrom(src => src.CarpetAreaSqMeter != null ? Math.Round(src.CarpetAreaSqMeter.Value, 2) : (double?)null))
            .ForMember(dest => dest.CarpetAreaSqFeet, opt => opt.MapFrom(src => src.CarpetAreaSqFeet != null ? Math.Round(src.CarpetAreaSqFeet.Value, 2) : (double?)null))
            .ForMember(dest => dest.BuiltupAreaSqMeter, opt => opt.MapFrom(src => src.BuiltupAreaSqMeter != null ? Math.Round(src.BuiltupAreaSqMeter.Value, 2) : (double?)null))
            .ForMember(dest => dest.BuiltupAreaSqFeet, opt => opt.MapFrom(src => src.BuiltupAreaSqFeet != null ? Math.Round(src.BuiltupAreaSqFeet.Value, 2) : (double?)null))
            .ForMember(dest => dest.CreatedDate, opt => opt.Ignore())
            .ForMember(dest => dest.CreatedBy, opt => opt.Ignore())
            .ForMember(dest => dest.UpdatedDate, opt => opt.Ignore())
            .ForMember(dest => dest.UpdatedBy, opt => opt.MapFrom(src => src.UpdatedBy));

        // PropertyEntity and PropertyDetailsEntity to AmenityPropertyDto (for response)
        CreateMap<PropertyEntity, AmenityPropertyDto>()
            .ForMember(dest => dest.PropertyDetailsId, opt => opt.Ignore())
            .ForMember(dest => dest.FloorId, opt => opt.Ignore())
            .ForMember(dest => dest.SubFloorId, opt => opt.Ignore())
            .ForMember(dest => dest.ConstructionTypeId, opt => opt.Ignore())
            .ForMember(dest => dest.TypeOfUseId, opt => opt.Ignore())
            .ForMember(dest => dest.SubTypeOfUseId, opt => opt.Ignore())
            .ForMember(dest => dest.NoOfRooms, opt => opt.Ignore())
            .ForMember(dest => dest.ConstructionYear, opt => opt.Ignore())
            .ForMember(dest => dest.AssessmentYear, opt => opt.Ignore())
            .ForMember(dest => dest.CarpetAreaSqMeter, opt => opt.Ignore())
            .ForMember(dest => dest.CarpetAreaSqFeet, opt => opt.Ignore())
            .ForMember(dest => dest.BuiltupAreaSqMeter, opt => opt.Ignore())
            .ForMember(dest => dest.BuiltupAreaSqFeet, opt => opt.Ignore())
            .ForMember(dest => dest.NoOfFloorAttachToAmenity, opt => opt.Ignore())
            .ForMember(dest => dest.DocumentType, opt => opt.Ignore())
            .ForMember(dest => dest.DocumentBindingId, opt => opt.Ignore())
            .ForMember(dest => dest.WorkflowStageId, opt => opt.Ignore())
            .ForMember(dest => dest.Bhk, opt => opt.Ignore())
            .ForMember(dest => dest.BHKId, opt => opt.Ignore())
            .ForMember(dest => dest.DocumentGuid, opt => opt.Ignore())
            .ForMember(dest => dest.NoOfFlat, opt => opt.Ignore())
            .ForMember(dest => dest.NoOfShop, opt => opt.Ignore())
            .ForMember(dest => dest.IsVerified, opt => opt.Ignore())
            .ForMember(dest => dest.IsMerged, opt => opt.Ignore())
            .ForMember(dest => dest.PropertyFloorId, opt => opt.Ignore());

        CreateMap<PropertyDetailsEntity, AmenityPropertyDto>()
            .ForMember(dest => dest.Id, opt => opt.Ignore())
            .ForMember(dest => dest.PropertyNo, opt => opt.Ignore())
            .ForMember(dest => dest.PartitionNo, opt => opt.Ignore())
            .ForMember(dest => dest.SocietyDetailId, opt => opt.Ignore())
            .ForMember(dest => dest.TaxZoneId, opt => opt.Ignore())
            .ForMember(dest => dest.CategoryId, opt => opt.Ignore())
            .ForMember(dest => dest.PropertyDetailsId, opt => opt.MapFrom(src => src.Id))
            .ForMember(dest => dest.PropertyFloorId, opt => opt.MapFrom(src => src.FloorId))
            .ForMember(dest => dest.NoOfFloorAttachToAmenity, opt => opt.Ignore())
            .ForMember(dest => dest.DocumentType, opt => opt.Ignore())
            .ForMember(dest => dest.DocumentBindingId, opt => opt.Ignore())
            .ForMember(dest => dest.PropertyTypeId, opt => opt.Ignore())
            .ForMember(dest => dest.WorkflowStageId, opt => opt.Ignore())
            .ForMember(dest => dest.Bhk, opt => opt.Ignore())
            .ForMember(dest => dest.BHKId, opt => opt.Ignore())
            .ForMember(dest => dest.DocumentGuid, opt => opt.Ignore())
            .ForMember(dest => dest.OpenPlot, opt => opt.Ignore())
            .ForMember(dest => dest.PropertySeqNo, opt => opt.Ignore())
            .ForMember(dest => dest.NoOfFlat, opt => opt.Ignore())
            .ForMember(dest => dest.NoOfShop, opt => opt.Ignore())
            .ForMember(dest => dest.IsVerified, opt => opt.Ignore())
            .ForMember(dest => dest.IsMerged, opt => opt.Ignore());
    }
}
